// Running Command:
// dart run comparison_operators.dart

// Example Output:
// Equal: false
// Not Equal: true
// Greater Than: true
// Less Than: false
// Greater Than or Equal: true
// Less Than or Equal: false
// -----------------------------------------

void main() {
  int a = 10;
  int b = 5;

  print("Equal: ${a == b}");
  print("Not Equal: ${a != b}");
  print("Greater Than: ${a > b}");
  print("Less Than: ${a < b}");
  print("Greater Than or Equal: ${a >= b}");
  print("Less Than or Equal: ${a <= b}");
}
